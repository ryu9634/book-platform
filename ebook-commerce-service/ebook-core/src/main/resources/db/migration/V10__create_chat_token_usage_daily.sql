-- 회원별 일일 토큰 사용량. 날짜별 행으로 쌓으면 자정이 지나면 자연히 새 행이 생기므로 초기화 배치가 필요 없고,
-- 지난 사용 이력이 그대로 남아 관리자 통계로 쓸 수 있습니다.
-- 캐시 토큰은 입력·출력과 단가가 달라 따로 셉니다.
CREATE SEQUENCE CHAT_TOKEN_USAGE_DAILY_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE CHAT_TOKEN_USAGE_DAILY (
    CHAT_TOKEN_USAGE_DAILY_ID  NUMBER(19)  NOT NULL,
    MEMBER_ID                  NUMBER(19)  NOT NULL,   -- 논리 참조: MEMBER
    USAGE_DATE                 DATE        NOT NULL,
    INPUT_TOKENS               NUMBER(12)  DEFAULT 0 NOT NULL,
    OUTPUT_TOKENS              NUMBER(12)  DEFAULT 0 NOT NULL,
    CACHE_CREATE_TOKENS        NUMBER(12)  DEFAULT 0 NOT NULL,
    CACHE_READ_TOKENS          NUMBER(12)  DEFAULT 0 NOT NULL,
    REQUEST_COUNT              NUMBER(10)  DEFAULT 0 NOT NULL,
    CREATED_AT                 TIMESTAMP   NOT NULL,
    UPDATED_AT                 TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CHAT_TOKEN_USAGE_DAILY            PRIMARY KEY (CHAT_TOKEN_USAGE_DAILY_ID),
    CONSTRAINT UK_CHAT_TOKEN_USAGE_DAILY_MEMBER_DATE UNIQUE (MEMBER_ID, USAGE_DATE)
);
CREATE INDEX IDX_CHAT_TOKEN_USAGE_DAILY_USAGE_DATE ON CHAT_TOKEN_USAGE_DAILY (USAGE_DATE);

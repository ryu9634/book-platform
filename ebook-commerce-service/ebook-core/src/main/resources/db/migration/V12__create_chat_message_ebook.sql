-- 답변에 제목이 나온 전자책. 화면과 API가 같은 추천 결과를 보여 주려면 메시지에 묶여 있어야 합니다.
-- 한 번 쓰고 사라지는 flash로 넘기면 새로 고칠 때나 API로 다시 읽을 때 사라집니다.
CREATE SEQUENCE CHAT_MESSAGE_EBOOK_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE CHAT_MESSAGE_EBOOK (
    CHAT_MESSAGE_EBOOK_ID  NUMBER(19)  NOT NULL,
    CHAT_MESSAGE_ID        NUMBER(19)  NOT NULL,   -- 논리 참조: CHAT_MESSAGE
    EBOOK_ID               NUMBER(19)  NOT NULL,   -- 논리 참조: EBOOK
    SORT_ORDER             NUMBER(5)   DEFAULT 0 NOT NULL,  -- 답변에 나온 순서
    CREATED_AT             TIMESTAMP   NOT NULL,
    UPDATED_AT             TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CHAT_MESSAGE_EBOOK              PRIMARY KEY (CHAT_MESSAGE_EBOOK_ID),
    CONSTRAINT UK_CHAT_MESSAGE_EBOOK_MESSAGE_EBOOK UNIQUE (CHAT_MESSAGE_ID, EBOOK_ID)
);
CREATE INDEX IDX_CHAT_MESSAGE_EBOOK_EBOOK_ID ON CHAT_MESSAGE_EBOOK (EBOOK_ID);

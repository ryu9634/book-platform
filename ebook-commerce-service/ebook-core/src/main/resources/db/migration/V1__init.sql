-- =====================================================================
-- ebook-commerce-service  초기 스키마  (스키마: EBOOK)
-- FK 제약 없음. 참조 무결성은 애플리케이션에서 검증하고, 참조 컬럼에는 인덱스를 둡니다.
-- 시퀀스 INCREMENT BY 50 은 JPA @SequenceGenerator(allocationSize = 50) 과 맞춘 값입니다.
-- =====================================================================

-- ---------- 시퀀스 ----------
CREATE SEQUENCE MEMBER_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE CATEGORY_SEQ       START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE EBOOK_SEQ          START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE CART_SEQ           START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE CART_ITEM_SEQ      START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE ORDERS_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE ORDER_ITEM_SEQ     START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE PAYMENT_SEQ        START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE BOOKSHELF_SEQ      START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE REVIEW_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE COUPON_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE MEMBER_COUPON_SEQ  START WITH 1 INCREMENT BY 50 NOCACHE;
-- 주문번호용: 사람이 읽는 번호이므로 1씩 증가 (JPA allocationSize 미적용)
CREATE SEQUENCE ORDER_NO_SEQ       START WITH 1 INCREMENT BY 1 NOCACHE;

-- ---------- MEMBER ----------
CREATE TABLE MEMBER (
    MEMBER_ID   NUMBER(19)          NOT NULL,
    LOGIN_ID    VARCHAR2(30 CHAR)   NOT NULL,
    PASSWORD    VARCHAR2(100 CHAR)  NOT NULL,
    NAME        VARCHAR2(50 CHAR)   NOT NULL,
    EMAIL       VARCHAR2(100 CHAR)  NOT NULL,
    ROLE        VARCHAR2(20)        DEFAULT 'USER'   NOT NULL,
    STATUS      VARCHAR2(20)        DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT  TIMESTAMP           NOT NULL,
    UPDATED_AT  TIMESTAMP           NOT NULL,
    CONSTRAINT PK_MEMBER          PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MEMBER_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UK_MEMBER_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT CK_MEMBER_ROLE     CHECK (ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT CK_MEMBER_STATUS   CHECK (STATUS IN ('ACTIVE', 'WITHDRAWN'))
);

-- ---------- CATEGORY ----------
CREATE TABLE CATEGORY (
    CATEGORY_ID  NUMBER(19)         NOT NULL,
    PARENT_ID    NUMBER(19),                    -- 논리 참조: CATEGORY. NULL이면 최상위
    NAME         VARCHAR2(50 CHAR)  NOT NULL,
    SORT_ORDER   NUMBER(5)          DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP          NOT NULL,
    UPDATED_AT   TIMESTAMP          NOT NULL,
    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID)
);
CREATE INDEX IDX_CATEGORY_PARENT_ID ON CATEGORY (PARENT_ID);

-- ---------- EBOOK ----------
CREATE TABLE EBOOK (
    EBOOK_ID         NUMBER(19)           NOT NULL,
    CATEGORY_ID      NUMBER(19),                     -- 논리 참조: CATEGORY
    ISBN             VARCHAR2(13 CHAR),
    TITLE            VARCHAR2(200 CHAR)   NOT NULL,
    AUTHOR           VARCHAR2(100 CHAR)   NOT NULL,
    PUBLISHER        VARCHAR2(100 CHAR),
    DESCRIPTION      VARCHAR2(4000 CHAR),
    COVER_IMAGE_URL  VARCHAR2(500 CHAR),
    PRICE            NUMBER(12)           NOT NULL,
    SALE_PRICE       NUMBER(12)           NOT NULL,
    FILE_KEY         VARCHAR2(300 CHAR),
    FILE_SIZE        NUMBER(12),
    PAGE_COUNT       NUMBER(6),
    STATUS           VARCHAR2(20)         DEFAULT 'ON_SALE' NOT NULL,
    PUBLISHED_DATE   DATE,
    SALES_COUNT      NUMBER(10)           DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMP            NOT NULL,
    UPDATED_AT       TIMESTAMP            NOT NULL,
    CONSTRAINT PK_EBOOK        PRIMARY KEY (EBOOK_ID),
    CONSTRAINT UK_EBOOK_ISBN   UNIQUE (ISBN),
    CONSTRAINT CK_EBOOK_STATUS CHECK (STATUS IN ('ON_SALE', 'STOP_SALE', 'HIDDEN')),
    CONSTRAINT CK_EBOOK_PRICE  CHECK (PRICE >= 0 AND SALE_PRICE >= 0 AND SALE_PRICE <= PRICE)
);
CREATE INDEX IDX_EBOOK_TITLE              ON EBOOK (TITLE);
CREATE INDEX IDX_EBOOK_CATEGORY_ID_STATUS ON EBOOK (CATEGORY_ID, STATUS);
CREATE INDEX IDX_EBOOK_STATUS_SALES_COUNT ON EBOOK (STATUS, SALES_COUNT DESC);

-- ---------- CART / CART_ITEM ----------
CREATE TABLE CART (
    CART_ID     NUMBER(19)  NOT NULL,
    MEMBER_ID   NUMBER(19)  NOT NULL,              -- 논리 참조: MEMBER
    CREATED_AT  TIMESTAMP   NOT NULL,
    UPDATED_AT  TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CART           PRIMARY KEY (CART_ID),
    CONSTRAINT UK_CART_MEMBER_ID UNIQUE (MEMBER_ID)
);

CREATE TABLE CART_ITEM (
    CART_ITEM_ID  NUMBER(19)  NOT NULL,
    CART_ID       NUMBER(19)  NOT NULL,            -- 논리 참조: CART
    EBOOK_ID      NUMBER(19)  NOT NULL,            -- 논리 참조: EBOOK
    CREATED_AT    TIMESTAMP   NOT NULL,
    UPDATED_AT    TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CART_ITEM                PRIMARY KEY (CART_ITEM_ID),
    CONSTRAINT UK_CART_ITEM_CART_ID_EBOOK_ID UNIQUE (CART_ID, EBOOK_ID)
);
CREATE INDEX IDX_CART_ITEM_EBOOK_ID ON CART_ITEM (EBOOK_ID);

-- ---------- COUPON / MEMBER_COUPON (v1: 테이블만, 로직은 v2) ----------
CREATE TABLE COUPON (
    COUPON_ID            NUMBER(19)          NOT NULL,
    NAME                 VARCHAR2(100 CHAR)  NOT NULL,
    DISCOUNT_TYPE        VARCHAR2(10)        NOT NULL,
    DISCOUNT_VALUE       NUMBER(12)          NOT NULL,
    MIN_ORDER_AMOUNT     NUMBER(12)          DEFAULT 0 NOT NULL,
    MAX_DISCOUNT_AMOUNT  NUMBER(12),
    VALID_FROM           TIMESTAMP           NOT NULL,
    VALID_TO             TIMESTAMP           NOT NULL,
    CREATED_AT           TIMESTAMP           NOT NULL,
    UPDATED_AT           TIMESTAMP           NOT NULL,
    CONSTRAINT PK_COUPON               PRIMARY KEY (COUPON_ID),
    CONSTRAINT CK_COUPON_DISCOUNT_TYPE CHECK (DISCOUNT_TYPE IN ('FIXED', 'RATE'))
);

CREATE TABLE MEMBER_COUPON (
    MEMBER_COUPON_ID  NUMBER(19)    NOT NULL,
    COUPON_ID         NUMBER(19)    NOT NULL,      -- 논리 참조: COUPON
    MEMBER_ID         NUMBER(19)    NOT NULL,      -- 논리 참조: MEMBER
    STATUS            VARCHAR2(20)  DEFAULT 'AVAILABLE' NOT NULL,
    USED_AT           TIMESTAMP,
    CREATED_AT        TIMESTAMP     NOT NULL,
    UPDATED_AT        TIMESTAMP     NOT NULL,
    CONSTRAINT PK_MEMBER_COUPON        PRIMARY KEY (MEMBER_COUPON_ID),
    CONSTRAINT CK_MEMBER_COUPON_STATUS CHECK (STATUS IN ('AVAILABLE', 'USED', 'EXPIRED'))
);
CREATE INDEX IDX_MEMBER_COUPON_MEMBER_ID_STATUS ON MEMBER_COUPON (MEMBER_ID, STATUS);
CREATE INDEX IDX_MEMBER_COUPON_COUPON_ID        ON MEMBER_COUPON (COUPON_ID);

-- ---------- ORDERS / ORDER_ITEM ----------
CREATE TABLE ORDERS (
    ORDER_ID          NUMBER(19)         NOT NULL,
    ORDER_NO          VARCHAR2(20 CHAR)  NOT NULL,
    MEMBER_ID         NUMBER(19)         NOT NULL,  -- 논리 참조: MEMBER
    MEMBER_COUPON_ID  NUMBER(19),                   -- 논리 참조: MEMBER_COUPON. NULL이면 쿠폰 미사용
    STATUS            VARCHAR2(20)       DEFAULT 'PENDING' NOT NULL,
    TOTAL_AMOUNT      NUMBER(12)         NOT NULL,
    DISCOUNT_AMOUNT   NUMBER(12)         DEFAULT 0 NOT NULL,
    PAID_AMOUNT       NUMBER(12)         NOT NULL,
    ORDERED_AT        TIMESTAMP          NOT NULL,
    PAID_AT           TIMESTAMP,
    CANCELED_AT       TIMESTAMP,
    CREATED_AT        TIMESTAMP          NOT NULL,
    UPDATED_AT        TIMESTAMP          NOT NULL,
    CONSTRAINT PK_ORDERS          PRIMARY KEY (ORDER_ID),
    CONSTRAINT UK_ORDERS_ORDER_NO UNIQUE (ORDER_NO),
    CONSTRAINT CK_ORDERS_STATUS   CHECK (STATUS IN ('PENDING', 'PAID', 'CANCELED', 'REFUNDED'))
);
CREATE INDEX IDX_ORDERS_MEMBER_ID_ORDERED_AT ON ORDERS (MEMBER_ID, ORDERED_AT DESC);
CREATE INDEX IDX_ORDERS_MEMBER_COUPON_ID     ON ORDERS (MEMBER_COUPON_ID);
CREATE INDEX IDX_ORDERS_STATUS_ORDERED_AT    ON ORDERS (STATUS, ORDERED_AT);

CREATE TABLE ORDER_ITEM (
    ORDER_ITEM_ID   NUMBER(19)          NOT NULL,
    ORDER_ID        NUMBER(19)          NOT NULL,  -- 논리 참조: ORDERS
    EBOOK_ID        NUMBER(19)          NOT NULL,  -- 논리 참조: EBOOK
    TITLE_SNAPSHOT  VARCHAR2(200 CHAR)  NOT NULL,
    PRICE_SNAPSHOT  NUMBER(12)          NOT NULL,
    STATUS          VARCHAR2(20)        DEFAULT 'ORDERED' NOT NULL,
    CREATED_AT      TIMESTAMP           NOT NULL,
    UPDATED_AT      TIMESTAMP           NOT NULL,
    CONSTRAINT PK_ORDER_ITEM                    PRIMARY KEY (ORDER_ITEM_ID),
    CONSTRAINT UK_ORDER_ITEM_ORDER_ID_EBOOK_ID  UNIQUE (ORDER_ID, EBOOK_ID),
    CONSTRAINT CK_ORDER_ITEM_STATUS             CHECK (STATUS IN ('ORDERED', 'REFUNDED'))
);
CREATE INDEX IDX_ORDER_ITEM_EBOOK_ID ON ORDER_ITEM (EBOOK_ID);

-- ---------- PAYMENT ----------
CREATE TABLE PAYMENT (
    PAYMENT_ID   NUMBER(19)          NOT NULL,
    ORDER_ID     NUMBER(19)          NOT NULL,      -- 논리 참조: ORDERS
    METHOD       VARCHAR2(20)        NOT NULL,
    AMOUNT       NUMBER(12)          NOT NULL,
    STATUS       VARCHAR2(20)        DEFAULT 'READY' NOT NULL,
    PG_TID       VARCHAR2(100 CHAR),
    FAIL_REASON  VARCHAR2(500 CHAR),
    APPROVED_AT  TIMESTAMP,
    CANCELED_AT  TIMESTAMP,
    CREATED_AT   TIMESTAMP           NOT NULL,
    UPDATED_AT   TIMESTAMP           NOT NULL,
    CONSTRAINT PK_PAYMENT          PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT UK_PAYMENT_ORDER_ID UNIQUE (ORDER_ID),
    CONSTRAINT CK_PAYMENT_METHOD   CHECK (METHOD IN ('CARD', 'KAKAOPAY', 'POINT', 'MOCK')),
    CONSTRAINT CK_PAYMENT_STATUS   CHECK (STATUS IN ('READY', 'APPROVED', 'FAILED', 'CANCELED'))
);

-- ---------- BOOKSHELF ----------
CREATE TABLE BOOKSHELF (
    BOOKSHELF_ID    NUMBER(19)  NOT NULL,
    MEMBER_ID       NUMBER(19)  NOT NULL,          -- 논리 참조: MEMBER
    EBOOK_ID        NUMBER(19)  NOT NULL,          -- 논리 참조: EBOOK
    ORDER_ITEM_ID   NUMBER(19)  NOT NULL,          -- 논리 참조: ORDER_ITEM (구매 근거)
    ACQUIRED_AT     TIMESTAMP   NOT NULL,
    LAST_READ_PAGE  NUMBER(6)   DEFAULT 0 NOT NULL,
    LAST_READ_AT    TIMESTAMP,
    IS_ACTIVE       NUMBER(1)   DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP   NOT NULL,
    UPDATED_AT      TIMESTAMP   NOT NULL,
    CONSTRAINT PK_BOOKSHELF                     PRIMARY KEY (BOOKSHELF_ID),
    CONSTRAINT UK_BOOKSHELF_MEMBER_ID_EBOOK_ID  UNIQUE (MEMBER_ID, EBOOK_ID),
    CONSTRAINT CK_BOOKSHELF_IS_ACTIVE           CHECK (IS_ACTIVE IN (0, 1))
);
CREATE INDEX IDX_BOOKSHELF_MEMBER_ID_ACTIVE ON BOOKSHELF (MEMBER_ID, IS_ACTIVE, LAST_READ_AT DESC);
CREATE INDEX IDX_BOOKSHELF_EBOOK_ID         ON BOOKSHELF (EBOOK_ID);
CREATE INDEX IDX_BOOKSHELF_ORDER_ITEM_ID    ON BOOKSHELF (ORDER_ITEM_ID);

-- ---------- REVIEW ----------
CREATE TABLE REVIEW (
    REVIEW_ID   NUMBER(19)           NOT NULL,
    EBOOK_ID    NUMBER(19)           NOT NULL,     -- 논리 참조: EBOOK
    MEMBER_ID   NUMBER(19)           NOT NULL,     -- 논리 참조: MEMBER
    RATING      NUMBER(1)            NOT NULL,
    CONTENT     VARCHAR2(2000 CHAR)  NOT NULL,
    CREATED_AT  TIMESTAMP            NOT NULL,
    UPDATED_AT  TIMESTAMP            NOT NULL,
    CONSTRAINT PK_REVIEW                    PRIMARY KEY (REVIEW_ID),
    CONSTRAINT UK_REVIEW_EBOOK_ID_MEMBER_ID UNIQUE (EBOOK_ID, MEMBER_ID),
    CONSTRAINT CK_REVIEW_RATING             CHECK (RATING BETWEEN 1 AND 5)
);
CREATE INDEX IDX_REVIEW_EBOOK_ID_CREATED_AT ON REVIEW (EBOOK_ID, CREATED_AT DESC);
CREATE INDEX IDX_REVIEW_MEMBER_ID           ON REVIEW (MEMBER_ID);

-- AI 챗봇 시스템 프롬프트. 추천 품질은 프롬프트 문장에 좌우되므로 재배포 없이 고칠 수 있게 DB에 둡니다.
CREATE SEQUENCE CHAT_PROMPT_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE CHAT_PROMPT (
    CHAT_PROMPT_ID  NUMBER(19)          NOT NULL,
    PROMPT_KEY      VARCHAR2(50 CHAR)   NOT NULL,   -- 용도 구분 (예: BOOK_RECOMMEND)
    NAME            VARCHAR2(100 CHAR)  NOT NULL,   -- 관리자 화면에 보여 줄 이름
    CONTENT         CLOB                NOT NULL,   -- 시스템 프롬프트 본문
    ENABLED         NUMBER(1)           DEFAULT 1 NOT NULL,
    UPDATED_BY      NUMBER(19),                     -- 논리 참조: MEMBER (마지막으로 고친 관리자)
    CREATED_AT      TIMESTAMP           NOT NULL,
    UPDATED_AT      TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CHAT_PROMPT            PRIMARY KEY (CHAT_PROMPT_ID),
    CONSTRAINT UK_CHAT_PROMPT_PROMPT_KEY UNIQUE (PROMPT_KEY),
    CONSTRAINT CK_CHAT_PROMPT_ENABLED    CHECK (ENABLED IN (0, 1))
);
CREATE INDEX IDX_CHAT_PROMPT_UPDATED_BY ON CHAT_PROMPT (UPDATED_BY);

-- 프롬프트 변경 이력. 문장을 고쳤다가 추천 품질이 나빠졌을 때 무엇으로 되돌릴지 알기 위해 바뀌기 전 본문을 남깁니다.
CREATE SEQUENCE CHAT_PROMPT_HISTORY_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE CHAT_PROMPT_HISTORY (
    CHAT_PROMPT_HISTORY_ID  NUMBER(19)  NOT NULL,
    CHAT_PROMPT_ID          NUMBER(19)  NOT NULL,   -- 논리 참조: CHAT_PROMPT
    CONTENT                 CLOB        NOT NULL,   -- 바뀌기 전 본문
    CHANGED_BY              NUMBER(19),             -- 논리 참조: MEMBER (고친 관리자)
    CREATED_AT              TIMESTAMP   NOT NULL,
    UPDATED_AT              TIMESTAMP   NOT NULL,
    CONSTRAINT PK_CHAT_PROMPT_HISTORY PRIMARY KEY (CHAT_PROMPT_HISTORY_ID)
);
CREATE INDEX IDX_CHAT_PROMPT_HISTORY_CHAT_PROMPT_ID ON CHAT_PROMPT_HISTORY (CHAT_PROMPT_ID, CREATED_AT DESC);

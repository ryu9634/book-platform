-- 회원별 대화 세션. 회원당 진행 중(ACTIVE) 세션은 하나이고, 새 대화를 시작하면 이전 세션을 CLOSED로 바꿉니다.
CREATE SEQUENCE CHAT_SESSION_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE CHAT_SESSION (
    CHAT_SESSION_ID  NUMBER(19)          NOT NULL,
    MEMBER_ID        NUMBER(19)          NOT NULL,   -- 논리 참조: MEMBER
    TITLE            VARCHAR2(100 CHAR),             -- 첫 질문을 줄여 목록에 보여 줍니다
    STATUS           VARCHAR2(20)        DEFAULT 'ACTIVE' NOT NULL,
    MESSAGE_COUNT    NUMBER(10)          DEFAULT 0 NOT NULL,
    LAST_MESSAGE_AT  TIMESTAMP,
    CREATED_AT       TIMESTAMP           NOT NULL,
    UPDATED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_CHAT_SESSION        PRIMARY KEY (CHAT_SESSION_ID),
    CONSTRAINT CK_CHAT_SESSION_STATUS CHECK (STATUS IN ('ACTIVE', 'CLOSED'))
);
CREATE INDEX IDX_CHAT_SESSION_MEMBER_ID_STATUS ON CHAT_SESSION (MEMBER_ID, STATUS, CHAT_SESSION_ID DESC);

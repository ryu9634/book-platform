-- 계정별 챗봇 설정. 행이 없으면 CHAT_SETTING의 기본값을 쓰므로 기존 회원을 채워 넣지 않아도 됩니다.
CREATE SEQUENCE MEMBER_CHAT_SETTING_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE MEMBER_CHAT_SETTING (
    MEMBER_CHAT_SETTING_ID  NUMBER(19)  NOT NULL,
    MEMBER_ID               NUMBER(19)  NOT NULL,   -- 논리 참조: MEMBER
    CHAT_ENABLED            NUMBER(1)   DEFAULT 1 NOT NULL,
    DAILY_TOKEN_LIMIT       NUMBER(12),             -- NULL이면 전역 기본 한도를 따릅니다
    UPDATED_BY              NUMBER(19),             -- 논리 참조: MEMBER (설정을 바꾼 관리자)
    CREATED_AT              TIMESTAMP   NOT NULL,
    UPDATED_AT              TIMESTAMP   NOT NULL,
    CONSTRAINT PK_MEMBER_CHAT_SETTING            PRIMARY KEY (MEMBER_CHAT_SETTING_ID),
    CONSTRAINT UK_MEMBER_CHAT_SETTING_MEMBER_ID  UNIQUE (MEMBER_ID),
    CONSTRAINT CK_MEMBER_CHAT_SETTING_ENABLED    CHECK (CHAT_ENABLED IN (0, 1)),
    CONSTRAINT CK_MEMBER_CHAT_SETTING_LIMIT      CHECK (DAILY_TOKEN_LIMIT IS NULL OR DAILY_TOKEN_LIMIT >= 0)
);
CREATE INDEX IDX_MEMBER_CHAT_SETTING_UPDATED_BY ON MEMBER_CHAT_SETTING (UPDATED_BY);

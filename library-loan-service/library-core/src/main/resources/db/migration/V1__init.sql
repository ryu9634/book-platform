-- =====================================================================
-- library-loan-service  초기 스키마  (스키마: LIBRARY)
-- FK 제약 없음. 참조 무결성은 애플리케이션에서 검증하고, 참조 컬럼에는 인덱스를 둡니다.
-- 시퀀스 INCREMENT BY 50 은 JPA @SequenceGenerator(allocationSize = 50) 과 맞춘 값입니다.
-- =====================================================================

-- ---------- 시퀀스 ----------
CREATE SEQUENCE MEMBER_SEQ       START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE CATEGORY_SEQ     START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE BOOK_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE BOOK_COPY_SEQ    START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE LOAN_SEQ         START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE RESERVATION_SEQ  START WITH 1 INCREMENT BY 50 NOCACHE;

-- ---------- MEMBER ----------
CREATE TABLE MEMBER (
    MEMBER_ID        NUMBER(19)          NOT NULL,
    LOGIN_ID         VARCHAR2(30 CHAR)   NOT NULL,
    PASSWORD         VARCHAR2(100 CHAR)  NOT NULL,
    NAME             VARCHAR2(50 CHAR)   NOT NULL,
    EMAIL            VARCHAR2(100 CHAR)  NOT NULL,
    PHONE            VARCHAR2(20 CHAR),
    ROLE             VARCHAR2(20)        DEFAULT 'USER'   NOT NULL,
    STATUS           VARCHAR2(20)        DEFAULT 'ACTIVE' NOT NULL,
    SUSPENDED_UNTIL  DATE,
    CREATED_AT       TIMESTAMP           NOT NULL,
    UPDATED_AT       TIMESTAMP           NOT NULL,
    CONSTRAINT PK_MEMBER          PRIMARY KEY (MEMBER_ID),
    CONSTRAINT UK_MEMBER_LOGIN_ID UNIQUE (LOGIN_ID),
    CONSTRAINT UK_MEMBER_EMAIL    UNIQUE (EMAIL),
    CONSTRAINT CK_MEMBER_ROLE     CHECK (ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT CK_MEMBER_STATUS   CHECK (STATUS IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

-- ---------- CATEGORY ----------
CREATE TABLE CATEGORY (
    CATEGORY_ID  NUMBER(19)         NOT NULL,
    PARENT_ID    NUMBER(19),                    -- 논리 참조: CATEGORY. NULL이면 최상위
    NAME         VARCHAR2(50 CHAR)  NOT NULL,
    SORT_ORDER   NUMBER(5)          DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP          NOT NULL,
    UPDATED_AT   TIMESTAMP          NOT NULL,
    CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORY_ID)
);
CREATE INDEX IDX_CATEGORY_PARENT_ID ON CATEGORY (PARENT_ID);

-- ---------- BOOK ----------
CREATE TABLE BOOK (
    BOOK_ID          NUMBER(19)           NOT NULL,
    CATEGORY_ID      NUMBER(19),                     -- 논리 참조: CATEGORY
    ISBN             VARCHAR2(13 CHAR),
    TITLE            VARCHAR2(200 CHAR)   NOT NULL,
    AUTHOR           VARCHAR2(100 CHAR)   NOT NULL,
    PUBLISHER        VARCHAR2(100 CHAR),
    PUBLISHED_DATE   DATE,
    DESCRIPTION      VARCHAR2(2000 CHAR),
    COVER_IMAGE_URL  VARCHAR2(500 CHAR),
    CREATED_AT       TIMESTAMP            NOT NULL,
    UPDATED_AT       TIMESTAMP            NOT NULL,
    CONSTRAINT PK_BOOK      PRIMARY KEY (BOOK_ID),
    CONSTRAINT UK_BOOK_ISBN UNIQUE (ISBN)
);
CREATE INDEX IDX_BOOK_TITLE       ON BOOK (TITLE);
CREATE INDEX IDX_BOOK_CATEGORY_ID ON BOOK (CATEGORY_ID);

-- ---------- BOOK_COPY ----------
CREATE TABLE BOOK_COPY (
    BOOK_COPY_ID  NUMBER(19)         NOT NULL,
    BOOK_ID       NUMBER(19)         NOT NULL,     -- 논리 참조: BOOK
    BARCODE       VARCHAR2(30 CHAR)  NOT NULL,
    STATUS        VARCHAR2(20)       DEFAULT 'AVAILABLE' NOT NULL,
    VERSION       NUMBER(10)         DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP          NOT NULL,
    UPDATED_AT    TIMESTAMP          NOT NULL,
    CONSTRAINT PK_BOOK_COPY         PRIMARY KEY (BOOK_COPY_ID),
    CONSTRAINT UK_BOOK_COPY_BARCODE UNIQUE (BARCODE),
    CONSTRAINT CK_BOOK_COPY_STATUS  CHECK (STATUS IN ('AVAILABLE', 'ON_LOAN', 'RESERVED', 'LOST', 'DISCARDED'))
);
CREATE INDEX IDX_BOOK_COPY_BOOK_ID_STATUS ON BOOK_COPY (BOOK_ID, STATUS);

-- ---------- LOAN ----------
CREATE TABLE LOAN (
    LOAN_ID       NUMBER(19)    NOT NULL,
    MEMBER_ID     NUMBER(19)    NOT NULL,          -- 논리 참조: MEMBER
    BOOK_COPY_ID  NUMBER(19)    NOT NULL,          -- 논리 참조: BOOK_COPY
    LOANED_AT     TIMESTAMP     NOT NULL,
    DUE_DATE      DATE          NOT NULL,
    RETURNED_AT   TIMESTAMP,
    STATUS        VARCHAR2(20)  DEFAULT 'ON_LOAN' NOT NULL,
    EXTEND_COUNT  NUMBER(2)     DEFAULT 0 NOT NULL,
    CREATED_AT    TIMESTAMP     NOT NULL,
    UPDATED_AT    TIMESTAMP     NOT NULL,
    CONSTRAINT PK_LOAN        PRIMARY KEY (LOAN_ID),
    CONSTRAINT CK_LOAN_STATUS CHECK (STATUS IN ('ON_LOAN', 'RETURNED', 'OVERDUE'))
);
CREATE INDEX IDX_LOAN_MEMBER_ID_STATUS  ON LOAN (MEMBER_ID, STATUS);
CREATE INDEX IDX_LOAN_BOOK_COPY_ID      ON LOAN (BOOK_COPY_ID);
CREATE INDEX IDX_LOAN_STATUS_DUE_DATE   ON LOAN (STATUS, DUE_DATE);

-- ---------- RESERVATION ----------
CREATE TABLE RESERVATION (
    RESERVATION_ID  NUMBER(19)    NOT NULL,
    MEMBER_ID       NUMBER(19)    NOT NULL,        -- 논리 참조: MEMBER
    BOOK_ID         NUMBER(19)    NOT NULL,        -- 논리 참조: BOOK
    RESERVED_AT     TIMESTAMP     NOT NULL,
    STATUS          VARCHAR2(20)  DEFAULT 'WAITING' NOT NULL,
    NOTIFIED_AT     TIMESTAMP,
    EXPIRES_AT      TIMESTAMP,
    CREATED_AT      TIMESTAMP     NOT NULL,
    UPDATED_AT      TIMESTAMP     NOT NULL,
    CONSTRAINT PK_RESERVATION        PRIMARY KEY (RESERVATION_ID),
    CONSTRAINT CK_RESERVATION_STATUS CHECK (STATUS IN ('WAITING', 'NOTIFIED', 'COMPLETED', 'CANCELED', 'EXPIRED'))
);
CREATE INDEX IDX_RESERVATION_BOOK_ID_STATUS   ON RESERVATION (BOOK_ID, STATUS, RESERVED_AT);
CREATE INDEX IDX_RESERVATION_MEMBER_ID_STATUS ON RESERVATION (MEMBER_ID, STATUS);
-- 활성 상태(WAITING, NOTIFIED)에서만 (회원, 도서) 중복 예약 금지: 함수 기반 유니크 인덱스
CREATE UNIQUE INDEX UK_RESERVATION_ACTIVE ON RESERVATION (
    CASE WHEN STATUS IN ('WAITING', 'NOTIFIED') THEN MEMBER_ID END,
    CASE WHEN STATUS IN ('WAITING', 'NOTIFIED') THEN BOOK_ID   END
);

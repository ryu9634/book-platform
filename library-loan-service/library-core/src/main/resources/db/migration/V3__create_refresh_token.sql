-- API 로그인(JWT)의 Refresh Token. 토큰 원문은 저장하지 않고 SHA-256 해시만 저장합니다.
CREATE SEQUENCE REFRESH_TOKEN_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE REFRESH_TOKEN (
    REFRESH_TOKEN_ID  NUMBER(19)        NOT NULL,
    MEMBER_ID         NUMBER(19)        NOT NULL,    -- 논리 참조: MEMBER
    TOKEN_HASH        VARCHAR2(64)      NOT NULL,    -- SHA-256 hex
    EXPIRES_AT        TIMESTAMP         NOT NULL,
    REVOKED_AT        TIMESTAMP,                     -- NULL이면 사용 가능
    CREATED_AT        TIMESTAMP         NOT NULL,
    UPDATED_AT        TIMESTAMP         NOT NULL,
    CONSTRAINT PK_REFRESH_TOKEN            PRIMARY KEY (REFRESH_TOKEN_ID),
    CONSTRAINT UK_REFRESH_TOKEN_TOKEN_HASH UNIQUE (TOKEN_HASH)
);
CREATE INDEX IDX_REFRESH_TOKEN_MEMBER_ID ON REFRESH_TOKEN (MEMBER_ID, REVOKED_AT);
